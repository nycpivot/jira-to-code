import uuid, os, base64, json, requests, pathlib, time, boto3

def push_files_to_branch_and_open_pr(work_item, code_path, model_signature) -> tuple[str, str]:

  issue_key = work_item.get("key") or ""
  guid = uuid.uuid4()

  base_branch = _get_default_branch()
  base_sha = _get_ref_sha(base_branch)
  branch_name  = f"codegen/{issue_key}-{guid}"

  _create_branch(branch_name, base_sha)

  # walk files under root_dir and upload
  commit_message = "chore(codegen): add generated files"

  root = pathlib.Path(code_path)
  for p in root.rglob("*"):
    if p.is_file():
      rel = p.relative_to(root).as_posix()
      _put_file(branch_name, rel, p.read_bytes(), commit_message)

  pr_title = f"Codegen by {model_signature} for {issue_key}"
  pr_body = f"Generated by {model_signature}, processed by Lambda for {issue_key}"
  pr_url = _create_pr(branch_name, base_branch, pr_title, pr_body)
  return branch_name, pr_url


